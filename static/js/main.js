        function switchLanguage(lang) {
            localStorage.setItem('billete_lang', lang);
            document.documentElement.lang = lang;
            
            const t = translations[lang];
            if (!t) return;

            // Update Text
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (t[key]) el.innerText = t[key];
            });

            // Update Placeholders
            const codeInput = document.getElementById('code');
            if (codeInput && t.ph_code) codeInput.placeholder = t.ph_code;
            
            const searchInput = document.getElementById('search_box');
            if (searchInput && t.ph_search) searchInput.placeholder = t.ph_search;

            // Update Select value
            const sel = document.getElementById('langSelect');
            if (sel) sel.value = lang;

            // Update Visual Card Text
            const vcTitle = document.getElementById('vc-title-text');
            if (vcTitle && t.vc_title) vcTitle.innerText = t.vc_title;

            const vcPaxTitle = document.getElementById('vc-pax-title-text');
            if (vcPaxTitle && t.vc_pax_title) vcPaxTitle.innerText = t.vc_pax_title;

            const vcFooter = document.getElementById('vc-footer-text');
            if (vcFooter && t.vc_wishes && t.vc_generated) {
                vcFooter.innerHTML = `${t.vc_wishes} &nbsp;|&nbsp; ${t.vc_generated}`;
            }

            // Re-render visual card if data exists
            if (lastProcessedData) {
                renderVisualCard(lastProcessedData);
                // Also update text result
                const newText = generateResultText(lastProcessedData);
                document.getElementById('result').textContent = newText;
            }

            // Update Stats if open
            if (document.getElementById('statsModal').style.display === 'block') {
                loadDetailedStats(currentStatsRange);
            }
        }

        // --- PDF Logic ---
        function downloadPDF() {
            if (!lastProcessedData) {
                showToast("Please process flight code first!", true);
                return;
            }
            
            const btn = document.getElementById('pdfBtn');
            const originalText = btn.innerHTML;
            btn.innerHTML = '⏳ Generating...';
            
            // Add terms to data payload
            const termsContent = document.getElementById('terms').value;
            // Ensure lastProcessedData exists and is valid
            if (!lastProcessedData || typeof lastProcessedData !== 'object') {
                 showToast("Invalid flight data", true);
                 btn.innerHTML = originalText;
                 return;
            }
            
            const payload = {
                ...lastProcessedData,
                terms: termsContent
            };

            fetch('/download_pdf', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(payload)
            })
            .then(response => {
                // Check content type
                const contentType = response.headers.get("content-type");
                if (contentType && contentType.includes("text/html")) {
                     throw new Error("Session expired. Please refresh and login again.");
                }
                if (!response.ok) throw new Error("Generation Failed: " + response.statusText);
                return response.blob();
            })
            .then(blob => {
                const url = window.URL.createObjectURL(blob);
                const a = document.createElement('a');
                a.href = url;
                a.download = "Itinerary.pdf";
                document.body.appendChild(a);
                a.click();
                a.remove();
                window.URL.revokeObjectURL(url);
                showToast("PDF Downloaded!");
            })
            .catch(err => {
                console.error(err);
                showToast("PDF Generation Failed", true);
            })
            .finally(() => {
                btn.innerHTML = originalText;
            });
        }

        // --- i18n Logic ---
        async function copyImage(blob) {
            try {
                await navigator.clipboard.write([
                    new ClipboardItem({
                        [blob.type]: blob
                    })
                ]);
                showToast('Image copied to clipboard!', 'success');
            } catch (err) {
                console.error('Failed to copy: ', err);
                const link = document.createElement('a');
                link.href = URL.createObjectURL(blob);
                link.download = 'flight-itinerary.png';
                link.click();
                showToast('Image downloaded (Copy failed)', 'success');
            }
        }

        function generateImage() {
            // Check if #visualCard works
            const paxes = document.getElementById('vc-pax-list').innerText;
            if (!paxes) {
                showToast('Please process flight code first!', 'error');
                // return;
            }

            const btn = document.getElementById('generateImageBtn');
            const originalText = btn.innerHTML;
            btn.innerText = 'Generating...';

            const captureArea = document.getElementById('visualCard');

            html2canvas(captureArea, {
                useCORS: true,
                scale: 2.5,
                backgroundColor: null,
                width: 800,
                windowWidth: 1200
            }).then(canvas => {
                canvas.toBlob(blob => {
                    copyImage(blob);
                    btn.innerHTML = originalText;
                });
            }).catch(err => {
                console.error(err);
                showToast('Failed to generate image', 'error');
                btn.innerHTML = originalText;
            });
        }

        function generateResultText(data) {
            const lang = document.documentElement.lang || 'zh';
            const t = translations[lang] || translations['zh'];
            
            let res = "";
            
            // Passengers
            data.passengers.forEach((p, idx) => {
                const name = p.name || p; // Support object or string
                const ticket = p.ticket ? `\n票号: ${p.ticket}` : "";
                res += `${t.txt_pax || 'Passenger'}${idx + 1}: ${name}${ticket}\n`;
            });

            // Flights
            const layovers = data.layovers || [];
            
            data.flights.forEach((f, idx) => {
                // Return trip marker
                const layover = layovers.find(l => l.flight_index === idx);
                if (layover && layover.type === 'return_split') {
                    res += `${t.txt_return || '---------<Return Trip>---------'}\n`;
                }
                
                // Date Line
                if (idx === 0 || (f.is_return || (layover && layover.type === 'return_split'))) {
                    let dateStr = t.txt_date || "【{y}-{m}-{d}】";
                    dateStr = dateStr.replace('{y}', f.year)
                                     .replace('{m}', f.month)
                                     .replace('{d}', f.day);
                    res += `${dateStr}\n`;
                }
                
                // Flight Line
                res += `${f.origin}-${f.dest}-->${f.start}-${f.end}`;
                if (f.next_day) res += "+1";
                res += "\n";

                // Layover Line
                if (layover && layover.type === 'layover' && layover.hours >= 0) {
                    let layStr = t.txt_layover || "Layover at {p}: {h}h {m}m";
                    layStr = layStr.replace('{p}', layover.place)
                                   .replace('{h}', layover.hours)
                                   .replace('{m}', layover.minutes);
                    res += `${layStr}\n`;
                }
            });
            
            // Luggage Info (Moved to bottom per request)
            if (data.luggage) {
                res += `\n${t.vc_eco_round || 'Economy Round Trip'}\n`; 
                
                const checkLabel = lang === 'zh' ? "托运行李" : (t.checked_luggage || "Checked");
                const handLabel = lang === 'zh' ? "手提行李" : (t.hand_luggage || "Hand");
                const unit = t.unit_piece || "pcs";
                const perPiece = lang === 'zh' ? ",每件" : ", each ";
                
                // Checked
                res += `${checkLabel}${data.luggage.pack_count} ${unit}${perPiece}${data.luggage.pack_weight}kg\n`;
                
                // Hand
                let handWeightStr = `${data.luggage.hand_weight}kg`;
                if (data.luggage.hand_count > 1) {
                    handWeightStr = `${perPiece}${data.luggage.hand_weight}kg`;
                } else {
                     handWeightStr = `${data.luggage.hand_weight} kg`;
                }
                res += `${handLabel}${data.luggage.hand_count} ${unit} ${handWeightStr}\n`;
            }
            
            // Terms (Added)
            const termsContent = document.getElementById('terms').value;
            if (termsContent && termsContent.trim()) {
                res += `\n${termsContent.trim()}\n`;
            }
            
            return res;
        }

