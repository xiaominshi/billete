        function downloadCalendar() {
            if (!lastProcessedData || !lastProcessedData.flights) {
                showToast("Please process flight code first!", true);
                return;
            }

            let icsContent = [
                "BEGIN:VCALENDAR",
                "VERSION:2.0",
                "PRODID:-//Billete//Flight Itinerary//EN"
            ];

            lastProcessedData.flights.forEach(f => {
                if (f.utc_start && f.utc_end) {
                    icsContent.push("BEGIN:VEVENT");
                    icsContent.push(`SUMMARY:Flight ${f.id} ${f.origin}-${f.dest}`);
                    icsContent.push(`DTSTART:${f.utc_start}`);
                    icsContent.push(`DTEND:${f.utc_end}`);
                    icsContent.push(`DESCRIPTION:Flight ${f.id} from ${f.origin} to ${f.dest}`);
                    icsContent.push(`LOCATION:${f.origin}`);
                    icsContent.push(`UID:${f.id}-${f.utc_start}@billete.local`);
                    icsContent.push("END:VEVENT");
                }
            });

            icsContent.push("END:VCALENDAR");

            const blob = new Blob([icsContent.join("\r\n")], { type: 'text/calendar;charset=utf-8' });
            const link = document.createElement('a');
            link.href = URL.createObjectURL(blob);
            link.download = "flight_itinerary.ics";
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
            showToast("Calendar file downloaded!");
        }

